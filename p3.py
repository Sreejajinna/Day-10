# Group One
a=" apple "
print(a)
print(len(a))
print(a.strip())
# it will remove the white spaces on both sides
print(a.lstrip())
# it will remove the white space on the left side
print(a.rstrip)
# it will remove the white space on the right side

# Group Two
b="banana"
c="SHINCHAN"
print(b.upper())
# convert it into Capital Alphate
print(b.lower())
# convert it into Smaller Alphate
print(b.isupper())
# check whether the letters is in uppercase or not
print(b.islower())
# check whether the letters is in lowercase or not
print(c.isupper())
print(c.islower())
